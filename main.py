def count_moods(data):
    happy_count = 0
    sad_count = 0

    for sentence, mood in data:
        if mood == "Happy":
            happy_count += 1
        elif mood == "Sad":
            sad_count += 1

    return (happy_count, sad_count)

print(count_moods(train_data))
happy_words = ["won", "surprise", "tasty", "excited", "selected", "learned", "favourite", "great"]
sad_words = ["lost", "failed", "moving", "cancelled", "upset", "stopped", "lonely", "missed"]

def guess_mood(sentence):
    words = sentence.lower()
    for punctuation in ".,!?;:":
        words = words.replace(punctuation, " ")

    words = words.split()
    happy_score = sum(1 for word in words if word in happy_words)
    sad_score = sum(1 for word in words if word in sad_words)

    if happy_score > sad_score:
        return "Happy"
    # Tie goes to Sad because negative or unclear clues should not be called Happy.
    return "Sad"

print(guess_mood("I won a medal!"))
print(guess_mood("I lost my notebook."))
practice_data = [
    ("I won a medal in the sports meet", "Happy"),
    ("I lost my notebook before the exam", "Sad"),
    ("My friends gave me a lovely surprise", "Happy"),
    ("The train was late and I felt upset", "Sad"),
    ("Today was a great day", "Happy"),
]

correct = 0

for sentence, actual_mood in practice_data:
    predicted_mood = guess_mood(sentence)
    print(sentence, "->", predicted_mood)
    if predicted_mood == actual_mood:
        correct += 1

accuracy = correct / len(practice_data) * 100
print("Accuracy:", accuracy, "%")